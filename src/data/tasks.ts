import type { Task } from '../types'
import { offsetIso } from '../utils/dates'

let counter = 0
function id(): string {
  counter += 1
  return `t${counter}`
}

interface Seed {
  title: string
  description?: string
  projectId: string
  status: Task['status']
  priority: Task['priority']
  assigneeId?: string
  dueOffset?: number
  tags?: string[]
  subtasks?: [string, boolean][]
  createdOffset?: number
}

function build(seed: Seed): Task {
  return {
    id: id(),
    title: seed.title,
    description: seed.description,
    status: seed.status,
    priority: seed.priority,
    projectId: seed.projectId,
    assigneeId: seed.assigneeId,
    dueDate: seed.dueOffset !== undefined ? offsetIso(seed.dueOffset) : undefined,
    tags: seed.tags ?? [],
    subtasks: (seed.subtasks ?? []).map(([title, completed], i) => ({
      id: `st${counter}-${i}`,
      title,
      completed,
    })),
    createdAt: offsetIso(seed.createdOffset ?? -20),
  }
}

